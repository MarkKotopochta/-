export const dialogueBank = Object.fromEntries(Object.entries({ ...entries, numbers: countable }).map(([topic, list]) => [
  topic, list.map(([zh, pinyin, inLine, ru = inLine, classifier]) => ({
    id: 'bank:' + zh, zh, pinyin, ru, inLine, classifier,
  })),
]));
export const bankWords = new Map(Object.values(dialogueBank).flat().map(word => [word.id, word]));
export const freeWordLimit = 100;

export function rememberBankWord(collection, id) {
  if (collection.has(id)) return 'saved';
  if (collection.size >= freeWordLimit) return 'full';
  collection.add(id);
  return 'added';
}
